USE ORG;

-- ORDER BY
SELECT * FROM WORKER
ORDER BY SALARY;

SELECT * FROM WORKER
ORDER BY SALARY DESC;


-- DISTINCT
SELECT DEPARTMENT
FROM WORKER;

SELECT DISTINCT DEPARTMENT
FROM WORKER;


-- GROUP BY
SELECT DEPARTMENT
FROM WORKER
GROUP BY DEPARTMENT;


-- COUNT
SELECT DEPARTMENT, COUNT(DEPARTMENT)
FROM WORKER
GROUP BY DEPARTMENT;


-- AVG
SELECT DEPARTMENT, AVG(SALARY)
FROM WORKER
GROUP BY DEPARTMENT;


-- MIN
SELECT DEPARTMENT, MIN(SALARY)
FROM WORKER
GROUP BY DEPARTMENT;


-- MAX
SELECT DEPARTMENT, MAX(SALARY)
FROM WORKER
GROUP BY DEPARTMENT;


-- SUM
SELECT DEPARTMENT, SUM(SALARY)
FROM WORKER
GROUP BY DEPARTMENT;


-- HAVING
SELECT DEPARTMENT, COUNT(DEPARTMENT)
FROM WORKER
GROUP BY DEPARTMENT
HAVING COUNT(DEPARTMENT) > 2;
